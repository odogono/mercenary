#!/usr/bin/env python3
"""Write Dion's complete static navigation references from census captures.

Run with PYTHONPATH=research/mercenary-iii-st. This writes documentation only;
it neither exports nor expands the playable Dion Data Payload.
"""
import argparse
from pathlib import Path

from m3lab.census_objects import extract_objects
from m3lab.census_locations import describe_cell, read_inventory, read_workspace
from m3lab.ram import Ram

REPOSITORY = Path(__file__).resolve().parents[3]


def code(value):
    return f'`{value}`'


def coords(values):
    return code(', '.join(map(str, values)))


def cell(number):
    return f'{number & 15:02d}-{number >> 4:02d}'


def instance(group, number):
    # A documentation reference to recovered original identities, not a payload ID.
    return f'{group}:{number:02X}'


def floor_map(floors):
    by_geometry = {}
    for binding in floors:
        by_geometry.setdefault(binding['geometrySlot'], []).append(binding['floor'])
    return '; '.join(f"{','.join(map(str, values))} → {geometry}"
                     for geometry, values in by_geometry.items()) or '—'


def table(headers, rows):
    return ('| ' + ' | '.join(headers) + ' |\n'
            + '| ' + ' | '.join('---' for _ in headers) + ' |\n'
            + ''.join('| ' + ' | '.join(map(str, row)) + ' |\n' for row in rows))


def write(run, docs):
    opening = Ram.load(run / 'start.ram')
    inventory = read_inventory(opening)
    objects = extract_objects(opening)
    groups = inventory['groups']
    bindings = {}
    captures = {}
    for group in groups:
        number = group['id']
        ram = Ram.load(run / 'all-groups' / f'group-{number:02d}.ram')
        captures[number] = ram
        current = {c['cell']: {**c, 'initial': True}
                   for c in read_workspace(ram, number)['cells']}
        for source in group['cells']:
            if source['slot'] and source['cell'] not in current:
                n = source['cell']
                entry = {**source, 'x': n & 15, 'z': n >> 4,
                         'origin': [(source[k] * 30 + 32768) & 65535 for k in ('dx', 'dz')]}
                current[n] = {**describe_cell(ram, entry), 'initial': False}
        bindings[number] = current
    midas = Ram.load(run / 'midas' / 'group-56-uniform.ram')
    midas_cells = read_workspace(midas, 56)['cells']
    if len(midas_cells) != 256 or {c['slot'] for c in midas_cells} != {68}:
        raise ValueError('MIDAS original-builder result disagrees')
    if sum(len(read_workspace(r, g)['cells']) for g, r in captures.items()) != 794:
        raise ValueError('initial full-group census disagrees')
    labels = {g['id']: {p['cell']: p['name'] for p in g['labels']} for g in groups}
    body_origins = {b['name']: b['records'] for b in inventory['bodies']}
    def host_name(o):
        return labels[o['group']].get(o['cell'], code(instance(o['group'], o['cell'])))
    def area_at(o):
        x, _, z = o['position']
        candidates = [p for p in body_origins[o['bodyName']]
                      if 0 <= ((x // 65536 - p['origin'][0]) % 4096) < 16
                      and 0 <= ((z // 65536 - p['origin'][1]) % 4096) < 16]
        return groups[candidates[0]['group']]['area'] or 'Open surface' if candidates else 'Open surface'

    object_text = '''# Dion object locations

This is the complete **246-slot persistent object census for Dion (Mercenary III)**,
recovered from a fresh start of the original ST game. It covers the whole Title,
including places beyond the opening Metis journeys currently admitted by the
browser implementation. Structures are listed in
[Dion structure locations](dion-structure-locations.md). The other Titles have
[Targ object locations](object-locations.md) and
[Damocles object locations](damocles-object-locations.md).

<!-- Generated by research/mercenary-iii-st/scripts/write-location-docs.py from original-game census captures. -->

The census accounts for **180 structure residents, 38 surface residents,
25 initially out-of-world slots, and three carried items**. Reserved, unnamed
and NULL-model slots retain their original identities; a listed slot is not
necessarily a visible or takeable object. The table records initial residence,
not the place an object ends up after play or scripts move it.

## Reading the table

- **Slot** is the original resident identity in decimal; **Hex** is the same
  identity in the research reports' notation. Names are decoded from MIII's own
  model records. **Record** is the bound model's source address; a dash means
  no model, rather than a missing object identity.
- **Body** identifies the surface. **Area / host** names the settlement and,
  for an indoor resident, its host. Unnamed hosts use **group:cell**: for example,
  `2:09` is group 2, cell `$09`. These are references to original records, not
  new payload instance IDs. Surface residents' stale group/cell metadata is
  not used to assign an indoor host.
- **Local cell X, Z** counts the two axes relative to that area's origin.
  **Body cell** is the
  unsigned Body Coordinate, `floor(X / 65536), floor(Z / 65536)`, on a
  4096-by-4096 surface. Body + Body cell identifies a location independently
  of an island or settlement. See the
  [group origins](dion-structure-locations.md#groups-and-origins).
- **Floor** is the indoor floor index, 0–10: 0 is G and 10 is B. It is distinct
  from Y and from the Body byte. **Exact X, Y, Z** retains the captured position
  in original units. Moving services, including the taxi, can already be
  circulating before the player calls them.
- Carried and out-of-world slots have no navigable coordinates. Their dummy or
  stale array positions are deliberately omitted.

Dion's browser implementation currently has no Shell Console `goto object`,
`get`, `drop` or `floor` commands. These tables also document original-game
content that its current playable payload does not yet contain.

## Complete object census

'''
    rows = []
    for o in objects['objects']:
        placed = o['residence'] in ('structure', 'surface')
        body = o['bodyName'] if placed else '—'
        local = floor = body_cell = position = '—'
        if placed:
            x, _, z = o['position']
            body_cell = coords([(x // 65536) % 4096, (z // 65536) % 4096])
            position = coords(o['position'])
            if o['residence'] == 'structure':
                area = groups[o['group']]['area'] or 'Unnamed area'
                host = host_name(o)
                residence = f'{area} / {host}'
                origin = next(p['origin'] for p in groups[o['group']]['placements']
                              if p['bodyName'] == o['bodyName'])
                local = coords([x // 65536 - origin[0], z // 65536 - origin[1]])
                floor = o['floor']
            else:
                residence = area_at(o) + ' / Surface'
                matches = [p for p in body_origins[o['bodyName']]
                           if groups[p['group']]['area'] == area_at(o)
                           and 0 <= (x // 65536 - p['origin'][0]) % 4096 < 16
                           and 0 <= (z // 65536 - p['origin'][1]) % 4096 < 16]
                if matches:
                    origin = matches[0]['origin']
                    local = coords([x // 65536 - origin[0], z // 65536 - origin[1]])
        else:
            residence = 'Carried' if o['residence'] == 'carried' else 'Out of world'
        rows.append([o['slot'], code(f"${o['slot']:02X}"), o['name'] or 'Unnamed slot',
                     body, residence, local, floor, body_cell, position,
                     code(o['modelRecord']) if o['hasModel'] else '—'])
    object_text += table(['Slot', 'Hex', 'Name or role', 'Body', 'Area / host',
                          'Local cell X, Z', 'Floor', 'Body cell X, Z',
                          'Exact X, Y, Z', 'Record'], rows)
    object_text += '''
The fresh Carried Stack is **104 TAXICARD, 103 BUS PASS, 135 ACME UNIVERSAL**, in
that order. **DOOR KEY A (slot 38, `$26`)** is initially at B. QUEUE LOCKSMITHS on GAEA;
the opening prison script subsequently sets its held bit, enabling the prison
door. The table retains its captured initial residence. NULL-model resident slots are
preserved, including slot 10, which participates in selection without geometry.

MIDAS objects 101 AUTHORS COMPUTER and 118 COFFEE TABLE are in the same repeated
structure at Body cell `2122, 3632`, local cell `393, 2694` relative to its group
origin. Their host record is `56:69`: the selector reduces the local coordinates
modulo 16, rather than placing them in the authored origin cell.

## Temporary slots and other model entries

**Slot 0** represents the current cell's structure. **Slots 247–255** are working
slots for cell-bound street furniture; they are rebound from ground templates,
so they have no single persistent object name or initial world residence. They
are accounted for separately from the 246 persistent slots. Identify a piece
of street furniture by its Body, cell, template ordinal and model entry.

The model table also contains non-resident records. For example, entries 263 and
264 are driver-head forms, and entry 318 supplies the taxi model that service
setup binds to resident 16. A model-table entry is not another independent
object slot. TOURCRAFT's original screen appearance at the opening spaceport
remains unconfirmed; its decoded identity and residence are recorded above.

## Sources and verification

All rows come from MIII's resident arrays and model/name table in the fresh
opening capture, independently of Damocles's Catalogue. The
[object decoder](../research/mercenary-iii-st/m3lab/census_objects.py) retains
per-record source ranges and hashes. The
[full recovery report](research/dion-full-location-recovery.md) records the
baseline, complete group inventory, original readers and source hashes.

The census exhausts persistent slots 1–246 and separately accounts for slots 0
and 247–255. Every one of the 180 structure residents was checked against its
original host's floor geometry and association hook, including MIDAS's uniform
workspace. Held bits agree with the original Carried Stack. The data was
recovered for these references; the playable `payload/dion/` is unchanged.
'''
    (docs / 'dion-object-locations.md').write_text(object_text)

    structure_text = '''# Dion structure locations

This is the complete original-game surface-structure reference for **Dion
(Mercenary III)**, covering all **57 structure groups** and their placements on
all **31 named Bodies**, including VOID's storage records. Object slots are
listed separately in [Dion object locations](dion-object-locations.md). The other
Titles have [Targ structure locations](structure-locations.md) and
[Damocles structure locations](damocles-structure-locations.md).

<!-- Generated by research/mercenary-iii-st/scripts/write-location-docs.py from original-game census captures. -->

The authored groups contain **795 distinct nonzero cell bindings**: 792 ordinary
surface cells, one MIDAS seed cell, and two VOID storage cells. One LOGOS
building starts absent, leaving **794 initial bindings** before MIDAS's
replication. MIDAS fills a repeating 16-by-16 workspace; its repetition is
specified below instead of enumerating every occurrence across the Body.

## Structure identities and coordinates

- **Instance** is written as **group:cell**, with group in decimal and cell in
  hexadecimal: `3:62` is METIS group 3, cell `$62`, TIMEWARP PRISON. This names
  recovered original records for this reference; it is not an invented
  browser Catalogue ID.
- **Local cell** is `X-Z` relative to the group's origin. The cell byte is
  `X + 16 × Z`. **Body cell** is the unsigned Body Coordinate, the group origin
  plus the local cell, wrapping each axis modulo 4096.
- **Selected slot → geometry** records the original nine-bit structure slot
  and its ground-floor geometry slot. An alias carries scale, palette, detail,
  storey pitch and a Floor Table; a direct record names its own geometry.
- **Record** is the ground-floor geometry's recovered source address.
  **Floors** lists nonzero geometry bindings for indices 0–10, rather than
  asserting every floor is reachable by a lift. Empty road structure 146 has
  no indoor floor. Floor 0 is G; Floor 10 is B.
- **Exact origin X, Z** is `(Body cell × 65536) + 32768 + (dx, dz) × 30`.
  It is the placed structure's origin, rather than its doorway or a resident's
  position. **Detail** is its building-detail index.

Shared geometry does not give its other placements the same name. Names come
from each group's own label table. A label can describe open ground or an area
without a cell structure; those names are retained explicitly below. Dion's
current browser implementation has no `goto` or `floor` console command, and
these references do not expand its currently playable Metis payload.

## Groups and origins

The table accounts for every group, including empty groups and bare islands.
An origin is a Body Coordinate, written in the signed form the original record
stores. Negative origins wrap modulo 4096 when locating a Body cell. Groups
with no Body placement are retained as unused definitions.

'''
    summary = []
    for g in groups:
        placed = '; '.join(f"{p['bodyName']} {coords(p['origin'])}" for p in g['placements']) or 'Unplaced group'
        summary.append([g['id'], code(g['stream']), g['area'] or '—', placed,
                        sum(c['slot'] != 0 for c in g['cells'])])
    structure_text += table(['Group', 'Stream', 'Area', 'Body and origin X, Z',
                             'Authored structure cells'], summary)
    structure_text += '''
## Named places

All decoded place labels are included. “Ground / label only” means the authored
cell has no structure binding; it is not a recovery gap. The initially absent
LOGOS construction site retains its future structure identity.

'''
    named = []
    for g in groups:
        for label_record in g['labels']:
            n = label_record['cell']
            c = bindings[g['id']].get(n)
            placement = g['placements'][0] if g['placements'] else None
            body = placement['bodyName'] if placement else '—'
            state = ('Initially present' if c['initial'] else 'Initially absent; construction') if c else 'Ground / label only'
            named.append([label_record['name'], body, g['area'] or '—',
                          code(cell(n)), code(instance(g['id'], n)),
                          f"{c['slot']} → {c['geometrySlot']}" if c else '—', state])
    structure_text += table(['Name', 'Body', 'Area', 'Local cell', 'Instance',
                             'Selected slot → geometry', 'Residence'], named)
    structure_text += '''
## Complete surface-structure catalogue

Each ordinary placed cell is listed once. The LOGOS record that starts cleared
is included with its state; MIDAS and VOID are accounted for in their own
sections. Road cells with empty structure geometry are included where the
original group gives them a nonzero slot.

'''
    for g in groups:
        if g['id'] in (49, 56) or not bindings[g['id']]:
            continue
        placement = g['placements'][0] if g['placements'] else None
        body = placement['bodyName'] if placement else 'Unplaced'
        origin = placement['origin'] if placement else None
        structure_text += f"### {body} — {g['area'] or 'Unnamed area'} (group {g['id']})\n\n"
        rows = []
        for n, c in sorted(bindings[g['id']].items()):
            bc = [(origin[0] + c['x']) % 4096, (origin[1] + c['z']) % 4096] if origin else None
            exact = [bc[i] * 65536 + c['origin'][i] for i in range(2)] if bc else None
            floors = ', '.join(str(f['floor']) for f in c['floors']) if c['geometrySlot'] != 146 else '—'
            name = labels[g['id']].get(n, '—')
            if not c['initial']:
                name += ' (initially absent; construction)'
            rows.append([code(instance(g['id'], n)), name, code(cell(n)),
                         coords(bc) if bc else '—', f"{c['slot']} → {c['geometrySlot']}",
                         code(c['record']), floors, coords(exact) if exact else '—', c['detail']])
        structure_text += table(['Instance', 'Name', 'Local cell', 'Body cell X, Z',
                                 'Selected slot → geometry', 'Record', 'Floors',
                                 'Exact origin X, Z', 'Detail'], rows) + '\n'
    seed = bindings[56][0]
    structure_text += f'''## MIDAS repeating field

Group **56**, THE MIDAS PROJECT, has origin **`1729, 938`** and one authored
seed binding, **`56:00`**, selected slot **{seed['slot']}**, geometry
**{seed['geometrySlot']}**, record **`{seed['record']}`**, detail **{seed['detail']}**.
The original MIDAS mode copies its structure word into **all 256 workspace
cells**, then selects cell coordinates modulo 16. Every Body cell therefore
uses this repeated structure, including cells far outside the origin window.

For a local cell `(x, z)`, its reference is `56:HH`, where
`HH = (x mod 16) + 16 × (z mod 16)`. Its unique physical location is Body
Coordinate `((1729 + x) mod 4096, (938 + z) mod 4096)`; its exact X/Z origin
is that Body Coordinate times 65,536 plus 32,768 on both axes. Its ground-floor
binding is **0 → 68**, with association 1 resident hooks in regions 2, 3 and 4.
The field's sixteen-cell period is not a list of only 256 physical buildings.

This rule includes the remote host of AUTHORS COMPUTER and COFFEE TABLE:
local cell `393, 2694`, repeated reference `56:69`, Body cell `2122, 3632`.

## VOID storage structures

VOID is Body offset 120, group 49 at origin `0, 0`. Its two cell bindings serve
the carried/out-of-world workspace, rather than navigable world destinations.

'''
    rows = [[code(instance(49, n)), code(cell(n)), f"{c['slot']} → {c['geometrySlot']}",
             code(c['record']), c['detail']] for n, c in sorted(bindings[49].items())]
    structure_text += table(['Instance', 'Storage cell', 'Selected slot → geometry',
                             'Record', 'Detail'], rows)
    structure_text += '''
## Structure slots and floor geometry

This indexes every selected structure slot in the authored census, including
the initially absent LOGOS building. **Slot record** is the alias or direct
record itself; the cell tables above give the ground-floor geometry address.
Floor bindings identify upper/interior geometry independently of the placed
slot. Direct road structure 146 has no indoor floor despite its empty geometry.

'''
    slots = {c['slot']: c for g in bindings.values() for c in g.values()}
    rows = []
    for slot, c in sorted(slots.items()):
        rows.append([slot, code(c['slotRecord']), coords(c['scale']),
                     c['detail'], c['pitch'] if c['pitch'] is not None else '—',
                     floor_map(c['floors']) if c['geometrySlot'] != 146 else '— (empty road geometry)'])
    structure_text += table(['Selected slot', 'Slot record', 'Scale X, Z', 'Detail',
                             'Storey pitch', 'Floor → geometry slot'], rows)
    structure_text += '''
## Sources and verification

The [full recovery report](research/dion-full-location-recovery.md) records the
pinned original-game capture, source ledgers, Body/group bindings, MIDAS mode,
and the initially cleared LOGOS building's construction restoration. The
[location decoder](../research/mercenary-iii-st/m3lab/census_locations.py)
retains provenance for every group and captured cell workspace.

All 57 groups were expanded by the original MIII workspace builder, stopped
at `$4F304` before service setup. Every resulting selected slot, scene selector,
dx and dz was compared to the decoded authored streams plus the initial state
overlay. There were no mismatches. A separate original-builder capture confirmed
all 256 MIDAS bindings. The census includes every nonzero authored cell binding,
every decoded place label, and explicitly accounts for empty/unplaced groups,
VOID and repeated field placements. No Damocles placement was used to fill a gap.
'''
    (docs / 'dion-structure-locations.md').write_text(structure_text)
    print(f"Wrote {len(rows)} structure-slot definitions, 795 authored cell bindings and 246 objects")


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--run', type=Path, required=True)
    parser.add_argument('--docs', type=Path, default=REPOSITORY / 'docs')
    args = parser.parse_args()
    write(args.run, args.docs)
