import { basename, resolve } from 'node:path';

// Writes docs/adr/README.md from each ADR's title; `--check` fails when it is stale.
const dir = resolve(import.meta.dir, '../../docs/adr');
const index = resolve(dir, 'README.md');
const rows: Array<string> = [];
for await (const path of new Bun.Glob('[0-9][0-9][0-9][0-9]-*.md').scan(dir)) {
  const title = (await Bun.file(resolve(dir, path)).text())
    .split('\n', 1)[0]!
    .replace(/^#\s*/, '');
  rows.push(`- [${basename(path).slice(0, 4)}](${path}) ${title}`);
}
rows.sort();
const text =
  '# Architecture Decision Records\n\n' +
  'Generated by `bun tools/adr-index.ts` in `web/`. A later ADR may supersede an earlier one in ' +
  'whole or in part; the superseded ADR says so near its top.\n\n' +
  rows.join('\n') +
  '\n';

if (process.argv.includes('--check')) {
  const current = await Bun.file(index)
    .text()
    .catch(() => '');
  if (current !== text) {
    process.stderr.write(
      'docs/adr/README.md is stale: run `bun tools/adr-index.ts` in web/\n'
    );
    process.exit(1);
  }
} else {
  await Bun.write(index, text);
}
