import { readFile, readdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

import {
  SOLUTIONS,
  ledgerDirectory,
  type ChapterLedger,
  type StepRecord
} from '../playthrough/ledger.ts';

/// Write the Gap Ledger note under `docs/research/` from the last run's chapter ledgers
/// (`bun run test:playthrough` writes them to `playthrough-results/ledger/`).
///
/// The note is generated: triage happens in the step table and in the issues it files, never by
/// editing the note. It carries no Damocles Display text, so no game text enters it from a run.

const NOTE = join(
  import.meta.dirname,
  '..',
  '..',
  'docs',
  'research',
  'damocles-solution-playthrough-ledger.md'
);

const cell = (text: string): string => text.replaceAll('|', String.raw`\|`);

const where = (step: StepRecord): string => {
  const target = step.target;
  if (target === null) {
    return '';
  }
  return [
    target.body,
    target.island,
    target.cell,
    target.floor === undefined ? undefined : `Floor ${target.floor}`
  ]
    .filter(part => part !== undefined)
    .join(' · ');
};

const clock = (seconds: number | undefined): string => {
  if (seconds === undefined || Number.isNaN(seconds)) {
    return '';
  }
  const sign = seconds < 0 ? '−' : '';
  const total = Math.round(Math.abs(seconds));
  const h = Math.floor(total / 3600);
  const m = Math.floor((total % 3600) / 60);
  const s = total % 60;
  return `${sign}${h}:${String(m).padStart(2, '0')}:${String(s).padStart(2, '0')}`;
};

const chapterSection = (ledger: ChapterLedger): string => {
  const counts = {
    failed: ledger.steps.filter(step => step.outcome === 'failed').length,
    notReached: ledger.steps.filter(step => step.outcome === 'not reached')
      .length,
    passed: ledger.steps.filter(step => step.outcome === 'passed').length
  };
  const lines = [
    `## ${ledger.title} (\`${ledger.chapter}\`)`,
    '',
    `Run ${ledger.started}. Start: ${ledger.setup.how}.`,
    ledger.setup.assumes.length === 0
      ? 'It assumes nothing a New Game does not give.'
      : `It assumes: ${ledger.setup.assumes.join('; ')}.`,
    '',
    `${counts.passed} passed, ${counts.failed} failed, ${counts.notReached} not reached. Page errors: ${ledger.pageErrors.length}.`,
    '',
    '| Step | Source | The step | Target | Outcome | Run time | Panel clock |',
    '| --- | --- | --- | --- | --- | --- | --- |'
  ];
  for (const step of ledger.steps) {
    lines.push(
      `| ${step.id} | ${step.cite.solution} ${step.cite.section} | ${cell(step.says)} | ${cell(where(step))} | ${step.outcome} | ${clock(step.evidence?.wallSeconds)} | ${step.evidence?.panel['clock'] ?? ''} |`
    );
  }
  const gaps = ledger.steps.filter(
    step => step.gap !== null || step.notes.length > 0
  );
  lines.push('', '### Gaps', '');
  if (gaps.length === 0) {
    lines.push('None in this chapter.');
  }
  for (const step of gaps) {
    for (const note of step.notes) {
      lines.push(
        `- **${step.id}, noted (did not stop the step).** ${cell(note)}`
      );
    }
    if (step.gap !== null) {
      lines.push(
        `- **${step.id}, ${step.gap.class}.** ${cell(step.gap.detail.split('\n')[0]!.replace(/[\s.]*$/, '.'))} The step had to prove that ${step.proves}.`
      );
    }
  }
  return lines.join('\n');
};

const main = async (): Promise<void> => {
  const names = (await readdir(ledgerDirectory()))
    .filter(name => name.endsWith('.json'))
    .sort((left, right) =>
      left
        .replace(/\.json$/, '')
        .localeCompare(right.replace(/\.json$/, ''), 'en', { numeric: true })
    );
  const ledgers = await Promise.all(
    names.map(
      async name =>
        JSON.parse(
          await readFile(join(ledgerDirectory(), name), 'utf8')
        ) as ChapterLedger
    )
  );
  const sources = Object.entries(SOLUTIONS).map(
    ([id, source]) => `- \`${id}\`: [${source.title}](${source.url})`
  );
  const note = [
    '# Damocles Solution Playthrough: Gap Ledger',
    '',
    'Generated by `bun tools/playthrough-ledger.ts` in `web/` from the last',
    '`bun run test:playthrough`. Do not edit by hand.',
    '',
    'A Solution Playthrough plays a published Damocles solution through the browser by player',
    'inputs alone. The solutions are hypothesis checklists, never Working-Authority Evidence',
    '([the behaviour catalogue’s research method](behavior-catalogue.md#research-method)), so',
    'a failed step is a lead until it is checked against the Working Authority. A harness gap is',
    'the steering’s failure, not the session’s; an unconfirmed lead is the session refusing a',
    'step. Triage turns a lead into a missing feature, a confirmed divergence or a solution error.',
    '',
    'Steps are paraphrased with a citation; no solution text is copied here. Sources:',
    '',
    ...sources,
    '',
    ...ledgers.map(chapterSection).flatMap(section => [section, '']),
    'Run time is wall-clock time from the chapter’s start to the end of each step. The panel',
    'clock is the Damocles Panel’s own clock at that moment, the time left before impact.',
    ''
  ].join('\n');
  await writeFile(NOTE, note);
  process.stdout.write(
    `wrote ${NOTE} from ${ledgers.length} chapter ledger(s)\n`
  );
};

await main();
